-- Clínica Alvorada data model (PLAN.md section 5).
-- Idempotent: safe to run many times. It never alters an existing table, so a
-- schema change requires recreating the database (docker compose down -v).
-- created_at is audit metadata set by the database clock: it is not
-- deterministic across seeds, so domain rules and evals must not depend on it.

CREATE EXTENSION IF NOT EXISTS vector;

CREATE TABLE IF NOT EXISTS patients (
  id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name       text NOT NULL,
  insurance  text,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS professionals (
  id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name       text NOT NULL,
  specialty  text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS appointments (
  id              integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  patient_id      integer NOT NULL REFERENCES patients (id),
  professional_id integer NOT NULL REFERENCES professionals (id),
  type            text NOT NULL,
  starts_at       timestamptz NOT NULL,
  status          text NOT NULL DEFAULT 'scheduled',
  created_at      timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT appointments_type_check
    CHECK (type IN ('evaluation', 'cleaning', 'orthodontic_maintenance', 'whitening')),
  CONSTRAINT appointments_status_check
    CHECK (status IN ('scheduled', 'completed')),
  -- Anti double booking: target of ON CONFLICT in book_appointment (PLAN.md 4.6).
  CONSTRAINT appointments_professional_starts_at_key UNIQUE (professional_id, starts_at),
  -- A patient cannot have two appointments at the same time.
  CONSTRAINT appointments_patient_starts_at_key UNIQUE (patient_id, starts_at)
);

CREATE TABLE IF NOT EXISTS chunks (
  id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  doc_id     text NOT NULL,
  title      text NOT NULL,
  section    text NOT NULL,
  content    text NOT NULL,
  source     text NOT NULL,
  embedding  vector(384) NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT chunks_source_check CHECK (source IN ('clinic', 'adversarial'))
);

CREATE INDEX IF NOT EXISTS chunks_embedding_hnsw_idx
  ON chunks USING hnsw (embedding vector_cosine_ops);
